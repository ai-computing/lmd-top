#!/usr/bin/env python3
"""List every plugin registered by the pinned router runner, without fetching code.
Usage: python3 scripts/epp-catalog.py /path/to/pinned/router > docs/EPP-PLUGINS.md
Fails on unresolved constants so an upgrade cannot silently produce a partial list.
"""
import re
import sys
from pathlib import Path
root = Path(sys.argv[1])
runner = (root / 'cmd/epp/runner/runner.go').read_text()
imports = {alias or path.rsplit('/', 1)[-1]: path for alias, path in re.findall(
    r'^\s*(?:(\w+)\s+)?"(github.com/llm-d/llm-d-router/[^\"]+)"', runner, re.M)}
rows = {}
for alias, const in re.findall(r'fwkplugin\.Register(?:WithPluginDependencies|AsDefaultProducer)?\((\w+)\.(\w+),', runner):
    path = imports[alias].removeprefix('github.com/llm-d/llm-d-router/')
    code = '\n'.join(p.read_text() for p in (root / path).glob('*.go') if not p.name.endswith('_test.go'))
    def resolve(folder, symbol, depth=0):
        if depth > 8:
            raise SystemExit('constant reference cycle')
        text = '\n'.join(p.read_text() for p in (root / folder).glob('*.go') if not p.name.endswith('_test.go'))
        match = re.search(r'\b' + re.escape(symbol) + r'\s*(?:string\s*)?=\s*"([^\"]+)"', text)
        if match:
            return match[1]
        ref = re.search(r'\b' + re.escape(symbol) + r'\s*=\s*(\w+)\.(\w+)', text)
        module_imports = {a or p.rsplit('/', 1)[-1]: p for a, p in re.findall(
            r'^\s*(?:(\w+)\s+)?"(github.com/llm-d/llm-d-router/[^\"]+)"', text, re.M)}
        if ref and ref[1] in module_imports:
            return resolve(module_imports[ref[1]].removeprefix('github.com/llm-d/llm-d-router/'), ref[2], depth+1)
        raise SystemExit(f'Unresolved plugin constant: {folder}.{symbol}')
    name = resolve(path, const)
    group = path.removeprefix('pkg/epp/framework/plugins/').rsplit('/', 1)[0]
    rows[name] = (group, path)
print('# Pinned EPP plugin inventory\n')
print('Source: llm-d-router `e194457dc507` (the version in contrib/epp-score-observer/go.mod).')
print('Registered types, including compatibility aliases and test plugins; registered does not mean enabled.')
print('Generated by scripts/epp-catalog.py from cmd/epp/runner/runner.go.\n')
print(f'{len(rows)} unique registered types. Additional factories registered elsewhere are outside this runner inventory.\n')
print('| Extension area | Plugin type | Source |\n|---|---|---|')
for name, (group, path) in sorted(rows.items(), key=lambda pair: (pair[1][0], pair[0])):
    print(f'| {group} | `{name}` | [code](https://github.com/llm-d/llm-d-router/tree/e194457dc507/{path}) |')
